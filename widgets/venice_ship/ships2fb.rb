#!/usr/bin/env ruby
# encoding: UTF-8

require 'firebase'

# ENV['FB_KEY'] = ''
SRC="https://vpc.firebaseio.com/"
firebase = Firebase::Client.new(SRC); #, ENV['FB_KEY']); nil

raise "navi già importate"
riga = 0
shipCapacities.each{|s|
  puts "Salvo #{riga += 1}/#{shipCapacities.size} #{s[:ShipName]}"
  firebase.set("dashboard/venice_ships/ship_capacities/#{s[:ShipName].downcase.strip.gsub(' ', '_')}", {
    name:       s[:ShipName],
    passengers: s[:Passengers],
    crew:       s[:Crew],
  })
}
